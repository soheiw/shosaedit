import assert from 'node:assert/strict';
import fs from 'node:fs';
import {armModelsSnapshot,parseArmModels,sequenceCalibration} from '../arm-calibration.js';
import {interpretedConfiguration} from '../recording-interpretation.js';
import {calibratedPackage,readStoredPackage} from '../calibrated-package.js';
import {readMotionFiles,validateRecording} from '../motion-files.js';
import {composeSequence} from '../motion-sequence.js';
const profile=JSON.parse(fs.readFileSync(new URL('../recording-references.json',import.meta.url))).find(p=>p.id==='alienware-model-a-20261030');
const joint=Array.from({length:8},(_,g)=>({motor:g-1,gain:1,axis:[1,0,0],pivot:[0,g,0]}));
const base={resolution:4096,R:{zero:Array(9).fill(100),joints:joint},L:{zero:Array(8).fill(100),joints:joint}};
const library={version:1,models:['Model A','Model B'],selected:{right:'Model A',left:'Model A'},calibrations:{right:{'Model A':profile.rest.R},left:{'Model A':profile.rest.L}}};
const before=JSON.stringify(library),s=armModelsSnapshot(library,{R:'Model A',L:'Model A'},base);
assert.equal(s.R.zero[3],1909);assert.equal(s.R.zero[4],2530);assert.deepEqual(s.R.rest,profile.rest.R.rest);
assert.equal(armModelsSnapshot(library,{R:'Model A',L:'Model A'},base,{convention:'rest-is-cad'}).R.zero[4],1506);
assert.throws(()=>armModelsSnapshot(library,{R:'Model B',L:'Model A'},base),/未登録/);
assert.equal(JSON.stringify(library),before);
const malformed=structuredClone(library);malformed.calibrations.right['Model A'].ids.reverse();assert.throws(()=>parseArmModels(malformed),/ID/);
const motion={format:'augmented-arms-motion',version:1,fps:30,name:'Test',calibrationSnapshot:s,R:[s.R.zero.slice(),s.R.zero.map(v=>v+1)],L:[s.L.zero.slice(),s.L.zero.map(v=>v-1)]};
const changedLibrary=structuredClone(library);changedLibrary.calibrations.right['Model A'].rest[3]=999;
assert.equal(interpretedConfiguration(base,motion).R.zero[3],1909,'snapshot unaffected by later library changes');
const zip=await calibratedPackage(motion,'Test'),file={name:'Test.zip',size:zip.length,arrayBuffer:async()=>zip.buffer};
const loaded=await readMotionFiles([file]);assert.deepEqual(loaded.R,motion.R);assert.deepEqual(loaded.L,motion.L);assert.deepEqual(loaded.calibrationSnapshot,s);
const files=readStoredPackage(zip);assert.equal(files.length,3);
const rawCsv=files.filter(f=>f.name.endsWith('.csv'));await assert.rejects(()=>readMotionFiles(rawCsv),/校正/);
assert.deepEqual((await readMotionFiles(rawCsv,{calibrationSnapshot:s})).R,motion.R);
const tampered=files.map(f=>f.name==='TestR.csv'?{...f,arrayBuffer:async()=>new TextEncoder().encode('0,0,0,0,0,0,0,0,0\r\n0,0,0,0,0,0,0,0,0\r\n').buffer}:f);
await assert.rejects(()=>readMotionFiles(tampered),/ハッシュ/);
const jsonFile={name:'Test.motion.json',size:100,text:async()=>JSON.stringify(motion)};
assert.deepEqual((await readMotionFiles([jsonFile])).calibrationSnapshot,s);
assert.deepEqual(validateRecording(motion).calibrationSnapshot,s);
assert.deepEqual(sequenceCalibration([motion,motion]).calibrationSnapshot,s);
assert.deepEqual(composeSequence([{clip:motion},{clip:motion}]).calibrationSnapshot,s);
const other=structuredClone(motion);other.calibrationSnapshot.R.zero[3]++;
assert.throws(()=>composeSequence([{clip:motion},{clip:other}]),/校正/);
assert.throws(()=>sequenceCalibration([motion,{...motion,calibrationSnapshot:undefined}]),/校正/);
console.log('PASS calibration import/IDs/missing models, explicit rest convention, immutable snapshots, CSV+JSON ZIP round trip, tamper rejection, raw CSV gating and sequence calibration conflicts');
